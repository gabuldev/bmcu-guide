"""Build data/hms-bmcu.json from data/hms-bmcu.source.json.

Downloads Bambu's official HMS lists (en, pt-BR, es), checks that every code
pattern in the source matches at least one official code, and attaches the
official texts so the app can show them without calling Bambu.

Usage: python3 scripts/build_hms.py [--cache DIR]
"""
import argparse, json, os, re, sys, urllib.request
from datetime import date

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "data", "hms-bmcu.source.json")
OUT = os.path.join(ROOT, "data", "hms-bmcu.json")
LANGS = ["en", "pt-BR", "es"]
URL = "https://e.bambulab.com/query.php?lang={}"


def load_official(cache):
    texts, version = {}, None
    for lang in LANGS:
        path = cache and os.path.join(cache, f"hms_{lang}.json")
        if path and os.path.exists(path):
            raw = json.load(open(path))
        else:
            with urllib.request.urlopen(URL.format(lang), timeout=30) as r:
                raw = json.load(r)
            if path:
                json.dump(raw, open(path, "w"))
        data = raw["data"]
        version = data["device_hms"]["ver"]
        for section in ("device_hms", "device_error"):
            for e in data[section][lang]:
                if e["intro"]:
                    texts.setdefault(e["ecode"].upper(), {})[lang] = e["intro"]
    return texts, version


def expand(pattern, codes):
    rx = re.compile("^" + pattern.upper().replace("?", "[0-9A-F]") + "$")
    return sorted(c for c in codes if rx.match(c))


def normalize_version(sw_ver):
    """'10.50.00.00' -> '10.5'; legacy '90.00.00.00' -> '9.0'."""
    major, minor = (int(x) for x in sw_ver.split(".")[:2])
    if major >= 60 and minor == 0:
        return f"{major // 10}.0"
    return f"{major}.{minor // 10}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", help="directory with/for hms_<lang>.json downloads")
    args = ap.parse_args()

    assert normalize_version("10.50.00.00") == "10.5"
    assert normalize_version("11.00.00.00") == "11.0"
    assert normalize_version("90.00.00.00") == "9.0"

    src = json.load(open(SRC))
    official, hms_ver = load_official(args.cache)

    errors, index = [], {}
    for prob in src["problems"]:
        for lang in LANGS:
            if lang not in prob["text"]:
                errors.append(f"{prob['id']}: missing text for {lang}")
        for key, confidence in (("codes", "confirmed"), ("possible_codes", "possible")):
            for pattern in prob.get(key, []):
                matches = expand(pattern, official)
                if not matches:
                    errors.append(f"{prob['id']}: pattern {pattern} matches no official code")
                for code in matches:
                    if code in index:
                        errors.append(f"{code} claimed by {index[code]['problem']} and {prob['id']}")
                    index[code] = {"problem": prob["id"], "confidence": confidence,
                                   "official": official[code]}
    if errors:
        sys.exit("\n".join(errors))

    out = {k: v for k, v in src.items() if k != "about"}
    out["about"] = "Generated by scripts/build_hms.py from hms-bmcu.source.json. Do not edit by hand."
    out["generated"] = date.today().isoformat()
    out["bambu_hms_version"] = hms_ver
    out["codes"] = dict(sorted(index.items()))
    with open(OUT, "w") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"{len(src['problems'])} problems, {len(index)} official codes mapped -> {OUT}")


if __name__ == "__main__":
    main()
